// 날짜('YYYY-MM-DD') → 그날 난수 (모두 같음)
export function dayRand(date, salt = 0) {
  let h = 2166136261 ^ salt; for (const ch of String(date)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return () => { h = Math.imul(h ^ (h >>> 15), 2246822507); h = Math.imul(h ^ (h >>> 13), 3266489909); h ^= h >>> 16; return (h >>> 0) / 4294967296; };
}
// 그날의 제보 (ok(r): 이 사람이 받을 수 있는가). 없으면 null
export function reportOf(date, ok = () => true) {
  const R = dayRand(date, 238), hoax = R() < REPORT.hoax;
  const can = REPORTS.filter((r) => ok(r)), pool = can.filter((r) => !!r.hoax === hoax);
  const list = pool.length ? pool : can; if (!list.length) return null;
  const caseOnes = list.filter((r) => r.case); // 열린 사건의 실마리가 있으면 그쪽을 조금 더 자주 (REPORT.caseK)
  if (!hoax && caseOnes.length && R() < REPORT.caseK) return caseOnes[Math.floor(R() * caseOnes.length)];
  return list[Math.floor(R() * list.length)];
}
